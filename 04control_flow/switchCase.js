const month = 5
switch (month) {  //month is the key which is to be compared in each case
    case 1:
        console.log("january")
        break;
    case 2:
        console.log("february")
        break;
    case 3:
        console.log("march")
        break;
    case 4:
        console.log("april")
        break;
    case 5:
        console.log("may")  //once the case matches further execution will be stopped bcoz of break statement used
        break;
    case 6:
        console.log("june")
        break;
    case 7:
        console.log("july")
        break;
    case 8:
        console.log("august")
        break;
    case 9:
        console.log("september")
        break;
    case 10:
        console.log("october")
        break;

    default:
        console.log("default case")
        break;
}